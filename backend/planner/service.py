"""Builds a complete trip plan: 3 route options, checkpoints, weather at ETA, risk, recommendation."""
import logging
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone

from . import heatmap
from .geo import RouteProfile, haversine_mi, offset_point, overlap_fraction, sample_checkpoints, simplify
from .providers import ProviderError, openmeteo, tomtom
from .recommend import rank, summarize
from .risk import LEVEL_NAMES, SEVERE, assess

log = logging.getLogger(__name__)

ROUTE_COUNT = 3
DISTINCT_OVERLAP = 0.85        # a route sharing >= 85% of its length with another is a duplicate
MAX_DETOUR_FACTOR = 2.0        # ignore via-point routes more than 2x the fastest route's length
VIA_OFFSETS = (0.2, -0.2, 0.4, -0.4)


def _is_distinct(candidate, chosen) -> bool:
    return all(overlap_fraction(candidate.points, c.points) < DISTINCT_OVERLAP and
               overlap_fraction(c.points, candidate.points) < DISTINCT_OVERLAP for c in chosen)


def get_three_routes(origin, destination, depart):
    """Three distinct truck routes from TomTom.

    TomTom is asked for 2 alternatives. If it returns fewer than 3 distinct routes
    (common on short trips), extra candidates are requested by routing through a
    circle placed to the side of the straight line between origin and destination.
    """
    notices = []
    # TomTom's own alternatives are "significantly different" by definition (alternativeType=anyRoute).
    chosen = list(tomtom.calculate_routes(origin, destination, depart, max_alternatives=2))

    if len(chosen) < ROUTE_COUNT:
        straight = haversine_mi(origin, destination)
        radius_m = int(min(135_000, max(2_000, straight * 1609.344 * 0.05)))

        def via_route(frac):
            try:
                via = offset_point(origin, destination, frac)
                return tomtom.calculate_routes(origin, destination, depart, max_alternatives=0,
                                               via=via, via_radius_m=radius_m)[0]
            except ProviderError as exc:
                log.info("via-point route %.2f failed: %s", frac, exc)
                return None

        with ThreadPoolExecutor(max_workers=len(VIA_OFFSETS)) as pool:
            candidates = [c for c in pool.map(via_route, VIA_OFFSETS) if c]
        limit = chosen[0].length_miles * MAX_DETOUR_FACTOR
        for c in sorted(candidates, key=lambda c: c.travel_seconds):
            if len(chosen) >= ROUTE_COUNT:
                break
            if c.length_miles <= limit and _is_distinct(c, chosen):
                chosen.append(c)
        added = sum(1 for c in chosen if c.source == "via-point")
        if added:
            notices.append(
                f"TomTom returned fewer than 3 distinct alternatives, so {added} route option(s) "
                "were generated by routing through an intermediate area to the side of the trip."
            )
    if len(chosen) < ROUTE_COUNT:
        notices.append(f"Only {len(chosen)} distinct route(s) exist between these points.")
    return chosen[:ROUTE_COUNT], notices


def build_plan(origin_q: str, destination_q: str, departure: datetime, load_lb: float,
               interval_miles: int) -> dict:
    with ThreadPoolExecutor(max_workers=2) as pool:
        origin, destination = pool.map(tomtom.geocode, [origin_q, destination_q])
    o, d = (origin.lat, origin.lon), (destination.lat, destination.lon)
    if haversine_mi(o, d) < 0.5:
        raise ProviderError("Origin and destination resolve to the same place.", status=422)

    now = datetime.now(timezone.utc)
    effective_departure = max(departure, now)
    depart_param = departure if departure > now + timedelta(minutes=1) else None

    raw_routes, notices = get_three_routes(o, d, depart_param)

    # Checkpoints every N route miles, with the truck's ETA at each.
    routes = []
    for i, raw in enumerate(raw_routes):
        profile = RouteProfile(raw.points, raw.length_miles, raw.travel_seconds, raw.anchors)
        routes.append({"raw": raw, "checkpoints": sample_checkpoints(profile, interval_miles),
                       "id": f"Route {chr(65 + i)}"})

    # One weather lookup for every checkpoint of every route.
    all_cps = [cp for r in routes for cp in r["checkpoints"]]
    longest = max(r["raw"].travel_seconds for r in routes)
    series = openmeteo.fetch_hourly([(cp.lat, cp.lon) for cp in all_cps],
                                    effective_departure, effective_departure + timedelta(seconds=longest))
    series_iter = iter(series)

    summaries, missing_weather = [], False
    for r in routes:
        cps_out, levels = [], []
        for cp in r["checkpoints"]:
            eta = effective_departure + timedelta(seconds=cp.seconds)
            wx = next(series_iter).at(eta.timestamp())
            missing_weather |= wx["missing"]
            risk = assess(wx["wind_mph"], wx["rain_in_hr"], wx["snow_in_hr"], load_lb)
            levels.append((risk.level, cp.covered_miles))
            cps_out.append({
                "index": cp.index,
                "mile": round(cp.mile, 1),
                "lat": round(cp.lat, 5),
                "lon": round(cp.lon, 5),
                "eta": eta.isoformat(timespec="minutes"),
                "wind_mph": wx["wind_mph"],
                "rain_in_hr": wx["rain_in_hr"],
                "snow_in_hr": wx["snow_in_hr"],
                "wind_level": LEVEL_NAMES[risk.wind_level],
                "rain_level": LEVEL_NAMES[risk.rain_level],
                "snow_level": LEVEL_NAMES[risk.snow_level],
                "level": risk.level,
                "level_name": risk.level_name,
                "load_rule": risk.load_rule,
                "covered_miles": round(cp.covered_miles, 2),
            })
        r["checkpoints_out"] = cps_out
        r["summary"] = summarize(r["id"], r["raw"].length_miles, r["raw"].travel_seconds, levels)
        summaries.append(r["summary"])

    ordered, reason = rank(summaries)
    rank_of = {s.route_id: i + 1 for i, s in enumerate(ordered)}
    best = ordered[0]
    if missing_weather:
        notices.append("Some forecast values were unavailable and were treated as zero.")
    if best.max_level >= SEVERE:
        notices.append(f"Even the recommended route has {LEVEL_NAMES[best.max_level]} conditions "
                       "at one or more checkpoints.")

    out_routes = []
    for r in routes:
        s = r["summary"]
        arrival = effective_departure + timedelta(seconds=r["raw"].travel_seconds)
        out_routes.append({
            "id": r["id"],
            "rank": rank_of[r["id"]],
            "recommended": r["id"] == best.route_id,
            "source": r["raw"].source,
            "geometry": [[round(la, 5), round(lo, 5)] for la, lo in simplify(r["raw"].points)],
            "summary": {
                "distance_miles": round(s.distance_miles, 1),
                "duration_seconds": round(s.duration_seconds),
                "arrival": arrival.isoformat(timespec="minutes"),
                "miles_by_level": s.miles_by_level,
                "average_risk": round(s.average_risk, 2),
                "max_level": s.max_level,
                "max_level_name": LEVEL_NAMES[s.max_level],
                "checkpoint_count": len(r["checkpoints_out"]),
            },
            "checkpoints": r["checkpoints_out"],
        })

    grid = heatmap.build_grid([r["raw"].points for r in routes])
    return {
        "origin": vars(origin),
        "destination": vars(destination),
        "departure": effective_departure.isoformat(timespec="minutes"),
        "load_weight_lb": load_lb,
        "interval_miles": interval_miles,
        "routes": out_routes,
        "recommendation": {"route_id": best.route_id, "reason": reason},
        "heatmap_grid": grid,
        "notices": notices,
    }
